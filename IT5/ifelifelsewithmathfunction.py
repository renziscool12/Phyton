import math

y = math.exp(22)
z = math.pi

if y < z:
    print("y is less than z")
elif y == z:
    print("Both values are the same")
else:
    print("None of them are correct")

x = math.sqrt(24)

if x % 2 == 0:
    print("x is an even number")
elif x % 6 == 0:
    print("x is divisible by 6")
else:
    print("x is an odd number")

